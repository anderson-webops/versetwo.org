"""Inspect the installed PDF renderer's print geometry; not a browser/AT audit.

Run with the same Python environment as the installed WeasyPrint CLI.
Only file/data resources are permitted. No PDF is generated by this check.
"""

import json
from pathlib import Path
from weasyprint import HTML
from weasyprint.formatting_structure.boxes import TextBox
from weasyprint.urls import URLFetcher

ROOT = Path(__file__).resolve().parents[1]


report = {}
for name, path, expected_pages in (
    ('packet', ROOT / 'prototype/print.html', 16),
    ('facilitator', ROOT / 'output/pdf/facilitator-outline.html', 1),
):
    fetcher = URLFetcher(allowed_protocols=('file', 'data'), fail_on_errors=True)
    document = HTML(filename=str(path), url_fetcher=fetcher).render()
    if len(document.pages) != expected_pages:
        raise ValueError(f'{name}: unexpected print page count')
    text_boxes = 0
    for number, page in enumerate(document.pages, 1):
        for box in page._page_box.descendants():
            if not isinstance(box, TextBox) or not box.text.strip():
                continue
            text_boxes += 1
            # Page bounds include footer counters. Check text geometry, not
            # container boxes that deliberately continue between pages.
            left, top = box.position_x, box.position_y
            right, bottom = left + box.width, top + box.height
            if left < -0.1 or top < -0.1 or right > page.width + 0.1 or bottom > page.height + 0.1:
                raise ValueError(f'{name}: text outside page {number}')
    report[name] = {
        'pages': len(document.pages),
        'nonempty_text_boxes': text_boxes,
        'text_within_page_bounds': 'pass',
        'resource_schemes': ['file', 'data'],
    }

(ROOT / 'docs/print-layout-checks.json').write_text(json.dumps(report, indent=2) + '\n')
print(json.dumps(report, indent=2))
